#!/bin/bash
echo "Creating a directory named 'my_test_dir'..."
# 创建一个名为 'my_test_dir' 的目录...
mkdir my_test_dir
echo "Directory created. Navigating into it..."
# 目录已创建。正在进入该目录...
cd my_test_dir
echo "Current directory:"
# 当前目录：
pwd
echo "Contents of 'my_test_dir':"
# 'my_test_dir' 的内容：
ls
echo "Script finished."
# 脚本结束。
